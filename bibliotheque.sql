DROP TABLE IF EXISTS emprunt, exemplaire, ecrire, livre, auteur, categorie, adherent CASCADE;

CREATE TABLE categorie (
    id_categorie  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    libelle       VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE auteur (
    id_auteur     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom           VARCHAR(60) NOT NULL,
    prenom        VARCHAR(60),
    nationalite   VARCHAR(40)
);

CREATE TABLE livre (
    id_livre        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cote            VARCHAR(12)  NOT NULL UNIQUE,
    titre           VARCHAR(200) NOT NULL,
    annee_parution  SMALLINT CHECK (annee_parution BETWEEN 1450 AND 2100),
    langue          CHAR(2) NOT NULL CHECK (langue IN ('fr', 'en', 'mg')),
    id_categorie    INTEGER NOT NULL REFERENCES categorie (id_categorie)
);

CREATE TABLE ecrire (
    id_auteur  INTEGER NOT NULL REFERENCES auteur (id_auteur),
    id_livre   INTEGER NOT NULL REFERENCES livre (id_livre),
    role       VARCHAR(20) NOT NULL DEFAULT 'auteur principal'
               CHECK (role IN ('auteur principal', 'co-auteur')),
    PRIMARY KEY (id_auteur, id_livre)
);

CREATE TABLE exemplaire (
    id_exemplaire     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code_barre        VARCHAR(20) NOT NULL UNIQUE,
    etat              VARCHAR(10) NOT NULL CHECK (etat IN ('neuf', 'bon', 'mauvais')),
    date_acquisition  DATE NOT NULL,
    id_livre          INTEGER NOT NULL REFERENCES livre (id_livre)
);

CREATE TABLE adherent (
    id_adherent       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom               VARCHAR(60)  NOT NULL,
    prenom            VARCHAR(60)  NOT NULL,
    email             VARCHAR(120) NOT NULL UNIQUE,
    date_inscription  DATE NOT NULL,
    id_parrain        INTEGER REFERENCES adherent (id_adherent),
    CHECK (id_parrain <> id_adherent)
);

CREATE TABLE emprunt (
    id_emprunt          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_emprunt        DATE NOT NULL,
    date_retour_prevue  DATE NOT NULL,
    date_retour         DATE,
    id_adherent         INTEGER NOT NULL REFERENCES adherent (id_adherent),
    id_exemplaire       INTEGER NOT NULL REFERENCES exemplaire (id_exemplaire),
    CHECK (date_retour_prevue > date_emprunt),
    CHECK (date_retour IS NULL OR date_retour >= date_emprunt)
);

